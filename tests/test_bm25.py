# ============================================================================
# test_bm25.py —— BM25 关键词检索的单元测试
#
# 【测什么】
#   验证 BM25 索引的构建、分词、打分、检索排序的正确性。
# ============================================================================

from rag.ingestion.bm25 import BM25Index, tokenize


# ----------------------------------------------------------------------------
# 测试 1：分词
# ----------------------------------------------------------------------------
def test_tokenize_chinese():
    tokens = tokenize("我爱北京天安门")
    assert "北京" in tokens          # jieba 能切出"北京"
    assert "天安门" in tokens        # 切出"天安门"


# ----------------------------------------------------------------------------
# 测试 2：索引构建 + 文档频率统计
# ----------------------------------------------------------------------------
def test_add_documents():
    bm = BM25Index()
    bm.add_documents(["机器学习是人工智能的分支", "深度学习是机器学习的子集"])
    assert len(bm.doc_tokens) == 2           # 2 篇文档
    # 注意：jieba 默认词典把"机器学习"切成"机器"+"学习"两个词，
    # 所以用分词后的实际词来断言，而非"机器学习"整词。
    assert bm.df["机器"] >= 1                # "机器"至少出现在一篇里
    assert bm.df["学习"] >= 1                # "学习"至少出现在一篇里
    assert bm.avg_len > 0                    # 平均长度已计算


# ----------------------------------------------------------------------------
# 测试 3：检索排序（相关文档得分更高）
# ----------------------------------------------------------------------------
def test_search_ranks_relevant_first():
    bm = BM25Index()
    docs = [
        "机器学习是人工智能的核心，深度学习是机器学习的重要方法",
        "今天天气很好，适合出去散步",
        "机器学习和深度学习都是人工智能的重要方向",
    ]
    bm.add_documents(docs)

    results = bm.search("机器学习 深度学习", top_k=2)
    # 最相关的应该是文档 0 和 2（都讲机器学习/深度学习），而非文档 1
    top_indices = [idx for idx, _ in results]
    assert 1 not in top_indices          # 文档 1（天气）不应进前 2
    assert len(results) == 2


# ----------------------------------------------------------------------------
# 测试 4：空查询 / 无匹配词
# ----------------------------------------------------------------------------
def test_search_no_match():
    bm = BM25Index()
    bm.add_documents(["机器学习是人工智能的分支"])
    results = bm.search("完全不相关的查询词", top_k=5)
    # 没有词匹配时，所有文档得分都是 0，但应仍返回结果（不报错）
    assert len(results) >= 0


# ----------------------------------------------------------------------------
# 测试 5：词频影响（同一词出现多的文档得分更高）
# ----------------------------------------------------------------------------
def test_term_frequency_affects_score():
    bm = BM25Index()
    docs = [
        "苹果 苹果 苹果 苹果 苹果",   # "苹果"出现 5 次（分词后）
        "苹果",                       # "苹果"出现 1 次
    ]
    bm.add_documents(docs)
    results = bm.search("苹果", top_k=2)
    # 文档 0（词频更高）应排第一；未传 ids 时 chunk_id 是序号字符串 "0"
    assert results[0][0] == "0"


# ----------------------------------------------------------------------------
# 测试 6：持久化（save/load）
# ----------------------------------------------------------------------------
def test_save_and_load(tmp_path):
    """BM25 索引保存到磁盘后，重新加载应完整恢复（无需重新分词）。"""
    bm = BM25Index()
    bm.add_documents(
        ["机器学习是人工智能的分支", "深度学习是机器学习的子集"],
        ids=["doc_a", "doc_b"],
    )

    # 保存前先记录检索结果
    before = bm.search("机器学习", top_k=2)

    path = tmp_path / "bm25.json"
    bm.save(path)

    # 重新加载
    bm2 = BM25Index()
    bm2.load(path)

    # 加载后检索结果应与保存前一致
    after = bm2.search("机器学习", top_k=2)
    assert before == after
    # chunk_id 正确恢复
    assert bm2.doc_ids == ["doc_a", "doc_b"]
    # 参数也恢复
    assert bm2.k1 == bm.k1
    assert bm2.b == bm.b
